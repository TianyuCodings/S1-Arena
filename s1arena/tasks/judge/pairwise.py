"""Leaf: pairwise preference with objective correctness (偏好两两比较).

Only subsets whose preferred response is objectively better are used: correct vs.
incorrect answers (checked against ground truth, unit tests or verifier functions)
and on-topic vs. off-topic answers. Every pair is asked in both orders with the gold
flipped, so a judge with a position bias cannot profit from it.
"""

from __future__ import annotations

import json

from ...registry import register_task
from ...schema import Gold, Question
from ..base import TaskAdapter
from ..common import hf_rows

LEAF = "judge/pairwise_preference"

# JudgeBench "vanilla" judge prompt (utils/templates/vanilla_prompt.jinja2), output-format lines removed.
JUDGEBENCH_INSTRUCTIONS = (
    "You are a helpful assistant in evaluating the quality of the outputs for a given instruction. Your goal is to "
    "select the best output for the given instruction. Select the Output (a) or Output (b) that is better for the "
    "given instruction. The two outputs are generated by two different AI chatbots respectively."
)
JUDGEBENCH_OPTIONS = {"a": "Output (a) is better.", "b": "Output (b) is better."}

# MT-Bench pairwise judge prompt as used for generative judges in RewardBench (rewardbench/generative.py,
# prompt_v2_gemini), output-format sentence removed.
MTBENCH_INSTRUCTIONS = (
    "Please act as an impartial judge and evaluate the quality of the responses provided by two AI assistants to the "
    "user question displayed below. You should choose the assistant that follows the user's instructions and answers "
    "the user's question better. Your evaluation should consider factors such as the helpfulness, relevance, accuracy, "
    "depth, creativity, and level of detail of their responses. Avoid any position biases and ensure that the order in "
    "which the responses were presented does not influence your decision. Do not allow the length of the responses to "
    "influence your evaluation. Do not favor certain names of the assistants. Be as objective as possible."
)
MTBENCH_OPTIONS = {"A": "Assistant A is better.", "B": "Assistant B is better."}


class PairwiseTask(TaskAdapter):
    """A prompt with a better and a worse response, asked with the better one first and then second."""

    leaf = LEAF
    tier = "B"
    items_per_record = 2
    instructions = MTBENCH_INSTRUCTIONS
    options = MTBENCH_OPTIONS
    state_keys = ("user_question", "assistant_a_answer", "assistant_b_answer")

    def pair(self, record, rng) -> tuple[str, str, str, dict]:
        """(prompt, better response, worse response, extra meta) for one record."""
        raise NotImplementedError

    def to_items(self, record, rng):
        prompt, better, worse, meta = self.pair(record, rng)
        first, second = list(self.options)
        items = []
        for order, (a, b, label) in (("better_first", (better, worse, first)), ("better_second", (worse, better, second))):
            state = dict(zip(self.state_keys, (prompt, a, b)))
            question = Question(type="choice", instructions=self.instructions, criteria=dict(self.options))
            items.append(self.item(state, {"better": question}, {"better": Gold(label=label)}, order=order, **meta))
        return items


@register_task
class JudgeBench(PairwiseTask):
    name = f"{LEAF}/judgebench"
    source = "JudgeBench, GPT-4o and Claude-3.5-Sonnet response pairs (Tan et al., 2025)"
    url = "https://huggingface.co/datasets/ScalerLab/JudgeBench"
    license = "MIT"
    tier = "A"
    criteria_source = "JudgeBench vanilla judge prompt (utils/templates/vanilla_prompt.jinja2), only the output-format lines removed"
    notes = ("Both responses come from the same model; exactly one reaches the ground-truth answer of the "
             "MMLU-Pro, LiveBench or LiveCodeBench question. Each pair is asked in both orders.")
    instructions = JUDGEBENCH_INSTRUCTIONS
    options = JUDGEBENCH_OPTIONS
    state_keys = ("instruction", "output_a", "output_b")

    def load(self):
        rows = []
        for split in ("gpt", "claude"):
            rows += hf_rows("ScalerLab/JudgeBench", None, split)
        # one pair has two identical responses yet a label; such pairs cannot differ in correctness
        return [r for r in rows if r["label"] in ("A>B", "B>A") and r["response_A"].strip() != r["response_B"].strip()]

    def label_of(self, record):
        family = "mmlu-pro" if record["source"].startswith("mmlu-pro") else record["source"]
        return f"{family}|{record['response_model']}"

    def pair(self, record, rng):
        a, b = record["response_A"], record["response_B"]
        better, worse = (a, b) if record["label"] == "A>B" else (b, a)
        meta = {"subset": record["source"], "response_model": record["response_model"], "original_id": record["pair_id"]}
        return record["question"], better, worse, meta


@register_task
class RMBench(PairwiseTask):
    name = f"{LEAF}/rm_bench"
    source = "RM-Bench, chat, math and code domains (Liu et al., 2025)"
    url = "https://huggingface.co/datasets/THU-KEG/RM-Bench"
    license = "ODC-BY"
    criteria_source = "MT-Bench pairwise judge prompt as used for generative judges in RewardBench, output-format sentence removed"
    notes = ("Math answers are checked against MATH ground truth and code against HumanEvalPack unit tests; chat "
             "pairs are GPT-4o answers vs. copies with injected factual errors, verified by annotators. Each prompt has "
             "three style variants (concise, detailed plain, detailed markdown) per side; one variant per side is drawn "
             "at random. The safety domain is left out because it is normative.")
    DOMAINS = ("chat", "math", "code")
    STYLES = ("concise", "detailed_plain", "detailed_markdown")

    def load(self):
        from huggingface_hub import hf_hub_download

        from ...env import load_env

        load_env()
        path = hf_hub_download("THU-KEG/RM-Bench", "total_dataset.json", repo_type="dataset")
        with open(path, encoding="utf-8") as f:
            rows = json.load(f)
        rows = [r for r in rows if r["domain"] in self.DOMAINS and len(r["chosen"]) == 3 and len(r["rejected"]) == 3]
        return [r for r in rows if not {c.strip() for c in r["chosen"]} & {x.strip() for x in r["rejected"]}]  # drops one record with identical texts

    def label_of(self, record):
        return record["domain"]

    def pair(self, record, rng):
        i, j = rng.randrange(3), rng.randrange(3)
        meta = {"domain": record["domain"], "better_style": self.STYLES[i], "worse_style": self.STYLES[j], "original_id": record["id"]}
        return record["prompt"], record["chosen"][i], record["rejected"][j], meta


@register_task
class RewardBench2(PairwiseTask):
    name = f"{LEAF}/reward_bench_2"
    source = "RewardBench 2, Math, Precise IF, Focus and Ties subsets (Malik et al., 2025)"
    url = "https://huggingface.co/datasets/allenai/reward-bench-2"
    license = "ODC-BY"
    criteria_source = "MT-Bench pairwise judge prompt as used for generative judges in RewardBench, output-format sentence removed"
    notes = ("Math: answers graded by majority voting and every sample manually verified; Precise IF: constraint "
             "adherence checked by verifier functions; Focus: the worse answer responds to a subtly rewritten prompt; "
             "Ties: manually written correct vs. incorrect answers. One rejected answer is drawn per prompt. The "
             "Factuality and Safety subsets are left out because their labels come from LLM judges.")
    SUBSETS = ("Math", "Precise IF", "Focus", "Ties")

    def load(self):
        rows = [r for r in hf_rows("allenai/reward-bench-2", None, "test") if r["subset"] in self.SUBSETS and r["chosen"] and r["rejected"]]
        return [r for r in rows if not {c.strip() for c in r["chosen"]} & {x.strip() for x in r["rejected"]}]

    def label_of(self, record):
        return record["subset"]

    def pair(self, record, rng):
        better = record["chosen"][rng.randrange(len(record["chosen"]))]
        worse = record["rejected"][rng.randrange(len(record["rejected"]))]
        return record["prompt"], better, worse, {"subset": record["subset"], "original_id": record["id"]}
