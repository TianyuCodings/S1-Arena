"""Generated items for knowledge and reasoning: dates, numbers and ordering puzzles.

Gold answers follow from the generation process, so labels are exact. The pools are
seeded by task name, so every build produces the same items. These leaves target
known weak spots of System-One models (dates compared as text, raw numbers, chained
comparisons).
"""

