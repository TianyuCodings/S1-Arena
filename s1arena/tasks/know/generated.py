CITIES = {  # city -> (IANA time zone, standard UTC offset in minutes)
    "New York": ("America/New_York", -300), "Chicago": ("America/Chicago", -360), "Los Angeles": ("America/Los_Angeles", -480),
    "London": ("Europe/London", 0), "Paris": ("Europe/Paris", 60), "Berlin": ("Europe/Berlin", 60),
    "Dubai": ("Asia/Dubai", 240), "Mumbai": ("Asia/Kolkata", 330), "Singapore": ("Asia/Singapore", 480),
    "Tokyo": ("Asia/Tokyo", 540), "Sydney": ("Australia/Sydney", 600), "Auckland": ("Pacific/Auckland", 720),
}
OFFSETS = [-600, -480, -420, -360, -300, -240, -180, 0, 60, 120, 180, 330, 345, 480, 540, 570, 600, 720]  # minutes
TRAPS = {  # kind -> trap types, cycled so each kind has a fixed share of pairs where a literal reading misleads
    "utc_offset": ("wall_clock", "none"),
    "city_time_zone": ("wall_clock", "dst", "none"),
    "twelve_hour": ("twelve", "none"),
    "day_month_order": ("day_month", "none"),
}


def _minutes(rng: random.Random, first_year: int, last_year: int) -> dt.datetime:
    start = dt.datetime(first_year, 1, 1)
    return start + dt.timedelta(minutes=rng.randrange((dt.datetime(last_year + 1, 1, 1) - start).days * 1440))


def _with_offset(local: dt.datetime, offset: int, rng: random.Random) -> str:
    """'2031-03-04T23:30-05:00' or '2031-03-04 23:30 UTC-5'."""
    sign, (h, m) = "-" if offset < 0 else "+", divmod(abs(offset), 60)
    if rng.random() < 0.5:
        return f"{local:%Y-%m-%dT%H:%M}{sign}{h:02d}:{m:02d}"
    return f"{local:%Y-%m-%d %H:%M} UTC{sign}{h}" + (f":{m:02d}" if m else "")


def _twelve(t: dt.datetime) -> str:
    return f"{MONTHS[t.month - 1]} {t.day}, {t.year}, {t.hour % 12 or 12}:{t.minute:02d} {'PM' if t.hour >= 12 else 'AM'}"


def _numeric(d: dt.date, style: str) -> str:
    if style == "iso":
        return d.isoformat()
    if style == "dmy":
        return f"{d.day:02d}/{d.month:02d}/{d.year} (DD/MM/YYYY)"
    return f"{d.month:02d}/{d.day:02d}/{d.year} (MM/DD/YYYY)"


@register_task
class TimestampCompare(Generated):
    name = "know/date_reasoning/timestamp_compare"
    leaf = "know/date_reasoning"
    source = "Timestamp comparison across time zones and formats (generated)"
    notes = ("Four kinds: UTC offsets, city time zones with daylight saving (2010-2024, IANA tz rules), 12-hour times near "
             "midnight and noon, and DD/MM vs MM/DD dates. In half of the pairs a literal reading gives the wrong order.")

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        makers = {"utc_offset": self._utc_offset, "city_time_zone": self._city, "twelve_hour": self._twelve_hour, "day_month_order": self._day_month}
        rows = []
        for i in range(POOL):
            kind = list(makers)[i % len(makers)]
            want = TRAPS[kind][(i // len(makers)) % len(TRAPS[kind])]
            while True:
                row = makers[kind](rng)
                if row and row["trap"] == want:
                    break
            if rng.random() < 0.5:
                row["a"], row["b"], row["earlier"] = row["b"], row["a"], not row["earlier"]
            rows.append({"a": row["a"], "b": row["b"], "label": "true" if row["earlier"] else "false", "kind": kind, "trap": want})
        return rows

    def _utc_offset(self, rng):
        a = _minutes(rng, 2000, 2035)
        b = a + dt.timedelta(minutes=rng.choice((-1, 1)) * rng.randint(10, 240))
        oa, ob = rng.sample(OFFSETS, 2)
        la, lb = a + dt.timedelta(minutes=oa), b + dt.timedelta(minutes=ob)
        if la == lb:
            return None
        return {"a": _with_offset(la, oa, rng), "b": _with_offset(lb, ob, rng), "earlier": a < b, "trap": "wall_clock" if (la < lb) != (a < b) else "none"}

    def _city(self, rng):
        from zoneinfo import ZoneInfo

        ca, cb = rng.sample(sorted(CITIES), 2)
        a = _minutes(rng, 2010, 2024).replace(tzinfo=dt.timezone.utc)
        b = a + dt.timedelta(minutes=rng.choice((-1, 1)) * rng.randint(10, 150))
        la, lb = a.astimezone(ZoneInfo(CITIES[ca][0])), b.astimezone(ZoneInfo(CITIES[cb][0]))
        if any(t.replace(fold=0).utcoffset() != t.replace(fold=1).utcoffset() for t in (la, lb)):
            return None  # the local time occurs twice when clocks go back
        wa, wb = la.replace(tzinfo=None), lb.replace(tzinfo=None)
        if wa == wb:
            return None
        sa, sb = wa - dt.timedelta(minutes=CITIES[ca][1]), wb - dt.timedelta(minutes=CITIES[cb][1])  # read with standard offsets
        if sa == sb:
            return None
        standard = (sa < sb) != (a < b)
        trap = "wall_clock" if (wa < wb) != (a < b) else "dst" if standard else "none"
        render = lambda t, city: f"{t.day} {MONTHS[t.month - 1]} {t.year}, {t:%H:%M} in {city}"
        return {"a": render(wa, ca), "b": render(wb, cb), "earlier": a < b, "trap": trap}

    def _twelve_hour(self, rng):
        a = _minutes(rng, 2000, 2035).replace(hour=rng.choice((0, 12)))  # 12:xx AM or 12:xx PM
        b = a + dt.timedelta(minutes=rng.choice((-1, 1)) * rng.randint(5, 120))
        literal = lambda t: (t.date(), (t.hour % 12 or 12) + (12 if t.hour >= 12 else 0), t.minute)  # reads 12 AM as 12, 12 PM as 24
        if literal(a) == literal(b):
            return None
        return {"a": _twelve(a), "b": _twelve(b), "earlier": a < b, "trap": "twelve" if (literal(a) < literal(b)) != (a < b) else "none"}

    def _day_month(self, rng):
        a = _minutes(rng, 2000, 2035).date()
        b = a + dt.timedelta(days=rng.choice((-1, 1)) * rng.randint(1, 75))
        sa, sb = rng.choice(("dmy", "mdy")), rng.choice(("dmy", "mdy", "iso"))
        if "dmy" not in (sa, sb) or any(d.day > 12 or d.day == d.month for d, s in ((a, sa), (b, sb)) if s != "iso"):
            return None  # both readings of every numeric date must be valid and differ
        us = lambda d, s: d if s != "dmy" else dt.date(d.year, d.day, d.month)  # read as MM/DD, ignoring the stated format
        if us(a, sa) == us(b, sb):
            return None
        return {"a": _numeric(a, sa), "b": _numeric(b, sb), "earlier": a < b, "trap": "day_month" if (us(a, sa) < us(b, sb)) != (a < b) else "none"}

    def label_of(self, record):  # trap type too, so no kind-and-trap cell leans towards one answer
        return f"{record['label']}|{record['kind']}|{record['trap']}"

    def to_item(self, record, rng):
        question = Question(type="boolean", instructions="Is the first point in time earlier than the second?")
        state = {"first_time": record["a"], "second_time": record["b"]}
        return self.item(state, {"earlier": question}, {"earlier": Gold(label=record["label"])}, kind=record["kind"], trap=record["trap"])


@register_task
class DateArithmetic(Generated):
    name = "know/date_reasoning/date_arithmetic"
    leaf = "know/date_reasoning"
    source = "Date arithmetic (generated)"
    notes = "Distractors are off by one day, by about a month, or by one year."

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        for _ in range(POOL):
            base = random_date(rng, 1950, 2049)
            days = rng.choice([rng.randint(1, 31), rng.randint(32, 120), rng.randint(121, 400)])
            direction = rng.choice(("after", "before"))
            target = base + dt.timedelta(days=days if direction == "after" else -days)
            candidates = {target, target + dt.timedelta(days=rng.choice((-1, 1))), shift_months(target, rng.choice((-1, 1))), shift_months(target, rng.choice((-12, 12)))}
            if len(candidates) < 4:
                continue
            bucket = "under_a_month" if days <= 31 else "under_4_months" if days <= 120 else "over_4_months"
            rows.append({"base": fmt_date(base, rng.choice(STYLES)), "days": days, "direction": direction,
                         "target": fmt_date(target, "mdy"), "candidates": sorted(fmt_date(c, "mdy") for c in candidates), "bucket": bucket})
        return rows

    def label_of(self, record):
        return f"{record['direction']}|{record['bucket']}"

    def to_item(self, record, rng):
        options, answer = letter_options(record["candidates"], record["target"], rng)
        question = Question(type="choice", instructions=f"Which date is {record['days']} days {record['direction']} the given date?", criteria=options)
        return self.item({"date": record["base"]}, {"date": question}, {"date": Gold(label=answer)}, bucket=record["bucket"])


def _pair(rng: random.Random, kind: str) -> tuple[str, str, float, float] | None:
    """Two numbers written in a given style; returns their text and values."""
    if kind == "decimal_digits":  # 9.11 vs 9.9
        k = rng.randint(0, 99)
        a, b = k + rng.randint(10, 99) / 100, k + rng.randint(1, 9) / 10
        return f"{a:.2f}", f"{b:.1f}", a, b
    if kind == "thousands":
        a = rng.randint(1_000, 9_999_999)
        b = a + rng.choice((-1, 1)) * rng.randint(1, max(1, a // 20))
        return f"{a:,}", str(b), a, b
    if kind == "scientific":
        mantissa, exponent = rng.randint(11, 99) / 10, rng.randint(2, 8)
        a = mantissa * 10**exponent
        b = round(a * rng.uniform(0.8, 1.25))
        return f"{mantissa}e{exponent}", f"{b:,}", a, b
    if kind == "fraction":
        q = rng.randint(3, 19)
        p = rng.randint(1, q - 1)
        a = p / q
        b = round(a + rng.choice((-1, 1)) * rng.uniform(0.005, 0.05), 3)
        return f"{p}/{q}", f"{b}", a, b
    if kind == "percent":
        a = rng.randint(1, 99)
        b = round(a / 100 + rng.choice((-1, 1)) * rng.uniform(0.01, 0.1), 2)
        return f"{a}%", f"{b}", a / 100, b
    a = -rng.randint(100, 9999) / 100  # negative numbers
    b = round(a + rng.choice((-1, 1)) * rng.uniform(0.01, 2), 2)
    return f"{a:.2f}", f"{b:.2f}", a, b


@register_task
class NumberCompare(Generated):
    name = "know/numeric_comparison/number_compare"
    leaf = "know/numeric_comparison"
    source = "Number comparison across notations (generated)"
    notes = "Decimals with different digit counts, thousands separators, scientific notation, fractions, percentages and negatives."

    KINDS = ("decimal_digits", "thousands", "scientific", "fraction", "percent", "negative")

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        for i in range(POOL):
            kind = self.KINDS[i % len(self.KINDS)]
            ta, tb, a, b = _pair(rng, kind)
            if a == b or ta == tb:
                continue
            if rng.random() < 0.5:
                ta, tb, a, b = tb, ta, b, a
            rows.append({"a": ta, "b": tb, "label": "true" if a > b else "false", "kind": kind})
        return rows

    def label_of(self, record):
        return f"{record['label']}|{record['kind']}"

    def to_item(self, record, rng):
        question = Question(type="boolean", instructions="Is the first number larger than the second number?")
        state = {"first_number": record["a"], "second_number": record["b"]}
        return self.item(state, {"larger": question}, {"larger": Gold(label=record["label"])}, kind=record["kind"])


def plain(v: float, decimals: int = 2) -> str:
    """12345.6 -> '12,345.6'; never scientific notation."""
    text = f"{v:,.{decimals}f}"
    return text.rstrip("0").rstrip(".") if "." in text else text


def decimals(v: float) -> int:
    """Two decimals, or three significant digits below 1 (0.249, not 0.25)."""
    return max(2, 2 - math.floor(math.log10(v)))


UNITS = {
    "length": {"millimetres": 0.001, "centimetres": 0.01, "metres": 1.0, "kilometres": 1000.0, "inches": 0.0254, "feet": 0.3048, "miles": 1609.344},
    "time": {"seconds": 1.0, "minutes": 60.0, "hours": 3600.0, "days": 86400.0, "weeks": 604800.0},
    "mass": {"grams": 1.0, "kilograms": 1000.0, "ounces": 28.349523125, "pounds": 453.59237},
}


@register_task
class UnitCompare(Generated):
    name = "know/numeric_comparison/unit_compare"
    leaf = "know/numeric_comparison"
    source = "Quantity comparison across units (generated)"
    notes = "Both values lie between 0.1 and 100,000; as displayed, the larger quantity exceeds the smaller by 2% to 25%."

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        while len(rows) < POOL:
            dimension = rng.choice(sorted(UNITS))
            units = UNITS[dimension]
            ua, ub = rng.sample(sorted(units), 2)
            ra = rng.uniform(0.5, 50)
            rb = ra * units[ua] * math.exp(rng.uniform(-math.log(1.25), math.log(1.25))) / units[ub]  # symmetric ratio
            if not 0.1 <= rb <= 100_000:  # e.g. millimetres against kilometres
                continue
            da, db = decimals(ra), decimals(rb)
            va, vb = round(ra, da), round(rb, db)
            qa, qb = va * units[ua], vb * units[ub]  # the label follows the displayed values
            if not 1.02 <= max(qa, qb) / min(qa, qb) <= 1.25:
                continue
            rows.append({"a": f"{plain(va, da)} {ua}", "b": f"{plain(vb, db)} {ub}", "label": "true" if qa > qb else "false", "dimension": dimension})
        return rows

    def label_of(self, record):
        return f"{record['label']}|{record['dimension']}"

    def to_item(self, record, rng):
        question = Question(type="boolean", instructions="Is the first quantity larger than the second quantity?")
        state = {"first_quantity": record["a"], "second_quantity": record["b"]}
        return self.item(state, {"larger": question}, {"larger": Gold(label=record["label"])}, dimension=record["dimension"])


NAMES = ["Alice", "Ben", "Chloe", "David", "Emma", "Farid", "Grace", "Hiro", "Ines", "Jamal", "Kira", "Liam"]
ATTRIBUTES = [  # comparative, opposite comparative, superlative, opposite superlative
    ("taller", "shorter", "tallest", "shortest"),
    ("older", "younger", "oldest", "youngest"),
    ("faster", "slower", "fastest", "slowest"),
    ("heavier", "lighter", "heaviest", "lightest"),
]
ORDINALS = ["", "second ", "third ", "fourth ", "fifth "]


@register_task
class OrderingPuzzle(Generated):
    name = "know/logic_puzzles/ordering"
    leaf = "know/logic_puzzles"
    source = "Ordering puzzles from pairwise clues (generated)"
    notes = "The clues determine a unique order; some clues are negated or phrased with the opposite comparative."

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        for _ in range(POOL):
            n = rng.choice((4, 5, 6))
            people = rng.sample(NAMES, n)  # people[0] has the most of the attribute
            more, less, most, least = rng.choice(ATTRIBUTES)
            clues = []
            for x, y in zip(people, people[1:]):
                style = rng.choice(("direct", "opposite", "negated"))
                if style == "direct":
                    clues.append(f"{x} is {more} than {y}.")
                elif style == "opposite":
                    clues.append(f"{y} is {less} than {x}.")
                else:
                    clues.append(f"{y} is not {more} than {x}.")
            if rng.random() < 0.5:  # one redundant but true clue
                i, j = sorted(rng.sample(range(n), 2))
                if j - i > 1:
                    clues.append(f"{people[i]} is {more} than {people[j]}.")
            rng.shuffle(clues)
            rank = rng.randrange(n)
            if rank == 0:
                ask, answer = f"Who is the {most}?", people[0]
            elif rank == n - 1:
                ask, answer = f"Who is the {least}?", people[-1]
            else:
                ask, answer = f"Who is the {ORDINALS[rank]}{most}?", people[rank]
            rows.append({"clues": clues, "people": sorted(people), "question": ask, "answer": answer, "n": n,
                         "form": "extreme" if rank in (0, n - 1) else "middle"})
        return rows

    def label_of(self, record):
        return f"{record['n']}|{record['form']}"

    def to_item(self, record, rng):
        options = {p: p for p in record["people"]}
        instructions = record["question"] + " Everyone differs, and the clues are all true."
        question = Question(type="choice", instructions=instructions, criteria=options)
        state = {"clues": " ".join(record["clues"])}
        return self.item(state, {"answer": question}, {"answer": Gold(label=record["answer"])}, people=record["n"], form=record["form"])
