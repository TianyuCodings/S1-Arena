@register_task
class PIITemplates(TaskAdapter):
    name = f"{LEAF}/templates"
    leaf = LEAF
    source = "Customer messages, forms and log lines with inserted personal information (generated)"
    url = "https://github.com/TianyuCodings/S1-Arena"
    license = GENERATED
    tier = "C"
    criteria_source = "Written; the PII types follow the examples of NIST SP 800-122 (Section 2.2); gold follows from the generation process"
    notes = ("Each text holds 0 to 4 PII types and 1 to 3 look-alikes that are not PII (order, tracking, invoice, ticket and SKU numbers, "
             "company names, delivery dates, cities, version numbers, social handles, web addresses). Card numbers pass the Luhn check, "
             "IBANs the mod-97 check and routing numbers the ABA check; names, numbers and addresses are fictitious. An independent "
             "regex-and-checksum checker agrees with every gold label.")

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        for i in range(POOL):
            k = rng.choices((0, 1, 2, 3, 4), weights=(1, 3, 3, 2, 1))[0]
            kinds = rng.sample(sorted(PII_TYPES), k)
            person = (rng.choice(FIRST), rng.choice(LAST))
            values = {kind: make_value(kind, rng, person) for kind in kinds}
            negatives = [make_negative(rng) for _ in range(rng.randint(1, 3))]
            genre = rng.choice(("email", "chat", "form", "log"))
            text = self.render(genre, values, negatives, rng)
            rows.append({"text": text, "genre": genre, "types": sorted(kinds), "negatives": sorted(n[0] for n in negatives)})
        return rows

    @staticmethod
    def render(genre: str, values: dict[str, str], negatives: list[tuple[str, str, str]], rng: random.Random) -> str:
        if genre == "form":
            lines = [f"{FORM[k]}: {v}" for k, v in values.items()] + [n[2] for n in negatives] + [f"Topic: {rng.choice(TOPICS)}"]
            rng.shuffle(lines)
            return "\n".join(["Contact form submission"] + lines)
        if genre == "log":
            fields = {"event": rng.choice(("login", "password_reset", "checkout", "profile_update")),
                      "status": rng.choice(("ok", "failed", "pending"))}
            fields.update({FORM[k].lower().replace(" ", "_"): v for k, v in values.items()})
            fields.update({n[2].split(":")[0].lower().replace(" ", "_"): n[2].split(": ", 1)[1] for n in negatives})
            items = list(fields.items())
            rng.shuffle(items)
            return json.dumps(dict(items), ensure_ascii=False)
        sentences = [rng.choice(PROSE[k]).format(v=v) for k, v in values.items()] + [n[1] for n in negatives]
        rng.shuffle(sentences)
        if genre == "chat":
            return " ".join([rng.choice(TOPICS)] + sentences)
        return "\n\n".join([rng.choice(OPENINGS), " ".join([rng.choice(TOPICS)] + sentences), rng.choice(CLOSINGS)])

    def label_of(self, record):
        return f"{len(record['types'])}|{record['genre']}"

    def to_item(self, record, rng):
        questions = {k: Question(type="boolean", instructions=text) for k, text in PII_TYPES.items()}
        gold = {k: Gold(label="true" if k in record["types"] else "false") for k in PII_TYPES}
        return self.item({"text": record["text"]}, questions, gold, genre=record["genre"], negatives=record["negatives"])


TAB = "https://raw.githubusercontent.com/NorskRegnesentral/text-anonymization-benchmark/master/echr_test.json"
# TAB annotation guidelines (Pilán et al., 2022, Appendix), verbatim.
TAB_DIRECT = ("Direct identifiers = text spans that contain information that directly and unequivocally identify the individual to be "
              "protected. Examples: person names (including nicknames/aliases and usernames), social security numbers, passport numbers.")
TAB_QUASI = ("Quasi-identifiers = Information that, in isolation, does not identify the individual to be protected but can do so, in "
             "combination with other quasi-identifiers and background knowledge. These will often refer to demographical (\"a 72-years "
             "old man\") or spatiotemporal attributes (\"on February 6 in Sevilla\").")
TAB_CONFIDENTIAL = ("Confidential attributes: information about the person's beliefs (religious or philosophical), political opinions, "
                    "sexual orientation or sex life, ethnic origin, or health.")


@register_task
class TABPassages(TaskAdapter):
    name = f"{LEAF}/tab"
    leaf = LEAF
    source = "Text Anonymization Benchmark (TAB), test split: ECHR court judgments annotated for anonymization (Pilán et al., 2022)"
    url = "https://github.com/NorskRegnesentral/text-anonymization-benchmark"
    license = "MIT"
    tier = "B"
    criteria_source = ("Direct and quasi-identifier definitions verbatim from the TAB annotation guidelines; confidential categories "
                       "from the TAB scheme (GDPR Article 9)")
    notes = ("Each item is one paragraph of a judgment plus the person the annotators were asked to protect (the applicant). The 127 test "
             "documents were annotated independently by 1 to 10 law students; soft label = share of annotators who marked at least one "
             "such span in the paragraph, hard label = majority (ties count as present). The texts are public judgments with real names.")

    def load(self):
        with fetch(TAB, "tab_echr_test.json").open(encoding="utf-8") as f:
            docs = json.load(f)
        rows = []
        for doc in docs:
            person = doc["task"].split("anonymise the following person:")[-1].strip()
            text = doc["text"]
            start = 0
            for para in text.split("\n"):
                begin, end = text.index(para, start), None
                end = begin + len(para)
                start = end
                if not 200 <= len(para) <= 2500:
                    continue
                votes = defaultdict(int)
                for annotation in doc["annotations"].values():
                    marks = set()
                    for m in annotation["entity_mentions"]:
                        if m["start_offset"] < begin or m["end_offset"] > end:
                            continue
                        if m["identifier_type"] == "DIRECT":
                            marks.add("direct")
                        if m["identifier_type"] == "QUASI":
                            marks.add("quasi")
                        if m.get("confidential_status") not in (None, "", "NOT_CONFIDENTIAL"):
                            marks.add("confidential")
                    for mark in marks:
                        votes[mark] += 1
                rows.append({"doc_id": doc["doc_id"], "person": person, "passage": para, "votes": dict(votes),
                             "annotators": len(doc["annotations"])})
        return rows

    @staticmethod
    def gold(votes: int, annotators: int) -> Gold:
        share = votes / annotators
        label = "true" if 2 * votes >= annotators else "false"
        return Gold(label=label, dist={"true": share, "false": 1.0 - share} if annotators >= 2 else None)

    def label_of(self, record):
        g = {k: self.gold(record["votes"].get(k, 0), record["annotators"]).label for k in ("direct", "confidential")}
        return f"{g['direct']}|{g['confidential']}"

    def to_item(self, record, rng):
        questions = {
            "direct_identifier": Question(type="boolean", instructions=f"Does the passage contain a direct identifier of the person to be protected? {TAB_DIRECT}"),
            "quasi_identifier": Question(type="boolean", instructions=f"Does the passage contain a quasi-identifier of the person to be protected? {TAB_QUASI}"),
            "confidential_attribute": Question(type="boolean", instructions=f"Does the passage reveal a confidential attribute of a person? {TAB_CONFIDENTIAL}"),
        }
        gold = {q: self.gold(record["votes"].get(key, 0), record["annotators"])
                for q, key in (("direct_identifier", "direct"), ("quasi_identifier", "quasi"), ("confidential_attribute", "confidential"))}
        state = {"person_to_protect": record["person"], "passage": record["passage"]}
        return self.item(state, questions, gold, doc_id=record["doc_id"], annotators=record["annotators"])
