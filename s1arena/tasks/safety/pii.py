def make_negative(rng: random.Random) -> tuple[str, str, str]:
    """(kind, prose sentence, form line) of a look-alike that is not personal information."""
    kind = rng.choice(("order", "tracking", "invoice", "company", "date", "city", "version", "sku", "ticket", "handle", "url"))
    if kind == "order":
        v = f"#{rng.randint(1000000, 9999999)}"
        return kind, f"It is about order {v}.", f"Order: {v}"
    if kind == "tracking":
        v = "1Z" + "".join(rng.choice(string.ascii_uppercase + string.digits) for _ in range(16))
        return kind, f"The tracking number {v} has not updated for a week.", f"Tracking: {v}"
    if kind == "invoice":
        v = f"INV-{rng.randint(2019, 2025)}-{rng.randint(100, 99999):05d}"
        return kind, f"The amount on invoice {v} looks wrong.", f"Invoice: {v}"
    if kind == "company":
        v = rng.choice(COMPANIES)
        return kind, f"I bought it from {v}.", f"Vendor: {v}"
    if kind == "date":
        v = f"{MONTHS[rng.randrange(12)]} {rng.randint(1, 28)}, {rng.randint(2022, 2026)}"
        return kind, rng.choice((f"The delivery was scheduled for {v}.", f"My appointment is on {v}.")), f"Requested date: {v}"
    if kind == "city":
        v = rng.choice(CITIES)
        return kind, f"I am currently based in {v}.", f"Region: {v}"
    if kind == "version":
        v = f"{rng.randint(1, 19)}.{rng.randint(0, 30)}.{rng.randint(0, 9)}"
        return kind, f"The app is on version {v}.", f"App version: {v}"
    if kind == "sku":
        v = f"SKU {rng.randint(100, 999)}-{rng.randint(1000, 9999)}-{rng.randint(10, 99)}"
        return kind, f"The item is {v}.", f"Item: {v}"
    if kind == "ticket":
        v = f"{rng.randint(10000, 99999)}"
        return kind, f"This follows up on ticket {v}.", f"Ticket: {v}"
    if kind == "handle":
        v = "@" + rng.choice(("sunny", "night", "blue", "code", "trail")) + "_" + rng.choice(("fox", "runner", "owl", "maker")) + str(rng.randint(1, 99))
        return kind, f"You may have seen my posts as {v}.", f"Forum handle: {v}"
    v = f"www.{rng.choice(COMPANIES).lower().replace(' ', '-')}.com/help"
    return kind, f"The help page at {v} did not answer my question.", f"Page: {v}"


