def luhn_digit(digits: str) -> str:
    total = 0
    for i, ch in enumerate(reversed(digits)):
        d = int(ch)
        if i % 2 == 0:
            d = d * 2 - 9 if d * 2 > 9 else d * 2
        total += d
    return str((10 - total % 10) % 10)


def iban(rng: random.Random) -> str:
    country, length = rng.choice((("DE", 18), ("GB", 18), ("FR", 23), ("NL", 14)))
    if country == "GB":
        bban = "".join(rng.choice(string.ascii_uppercase) for _ in range(4)) + "".join(rng.choice(string.digits) for _ in range(14))
    elif country == "NL":
        bban = "".join(rng.choice(string.ascii_uppercase) for _ in range(4)) + "".join(rng.choice(string.digits) for _ in range(10))
    else:
        bban = "".join(rng.choice(string.digits) for _ in range(length))
    numeric = "".join(str(int(ch, 36)) for ch in bban + country + "00")
    check = 98 - int(numeric) % 97
    raw = f"{country}{check:02d}{bban}"
    return " ".join(raw[i:i + 4] for i in range(0, len(raw), 4))


def aba_routing(rng: random.Random) -> str:
    while True:
        d = [rng.randint(0, 9) for _ in range(8)]
        for last in range(10):
            n = d + [last]
            if (3 * (n[0] + n[3] + n[6]) + 7 * (n[1] + n[4] + n[7]) + (n[2] + n[5] + n[8])) % 10 == 0:
                return "".join(map(str, n))


def make_value(kind: str, rng: random.Random, person: tuple[str, str]) -> str:
    first, last = person
    if kind == "person_name":
        return f"{first} {last}"
    if kind == "email_address":
        user = rng.choice((f"{first}.{last}", f"{first[0]}{last}", f"{first}{rng.randint(1, 99)}", f"{last}.{first[0]}"))
        return f"{user.lower().replace(' ', '').replace(chr(39), '')}@{rng.choice(MAIL_DOMAINS)}"
    if kind == "phone_number":
        style = rng.randrange(4)
        if style == 0:
            return f"({rng.randint(201, 989)}) 555-{rng.randint(100, 199):04d}"
        if style == 1:
            return f"+1 {rng.randint(201, 989)}-555-{rng.randint(100, 199):04d}"
        if style == 2:
            return f"+44 20 7946 {rng.randint(0, 999):04d}"
        return f"+49 30 {rng.randint(10000000, 99999999)}"
    if kind == "street_address":
        city, state = rng.choice(US_CITIES)
        return f"{rng.randint(2, 9899)} {rng.choice(STREETS)} {rng.choice(SUFFIXES)}, {city}, {state} {rng.randint(10000, 99999)}"
    if kind == "date_of_birth":
        y, m, d = rng.randint(1941, 2006), rng.randint(1, 12), rng.randint(1, 28)
        return rng.choice((f"{MONTHS[m - 1]} {d}, {y}", f"{d} {MONTHS[m - 1]} {y}", f"{y}-{m:02d}-{d:02d}", f"{m:02d}/{d:02d}/{y}"))
    if kind == "government_id":
        style = rng.randrange(3)
        if style == 0:
            return f"SSN {rng.randint(100, 665):03d}-{rng.randint(10, 99):02d}-{rng.randint(1000, 9999):04d}"
        if style == 1:
            return f"passport number {rng.choice(string.ascii_uppercase)}{rng.randint(10000000, 99999999)}"
        return f"driver's license number {rng.choice(string.ascii_uppercase)}{rng.randint(1000000, 9999999)}"
    if kind == "payment_card":
        body = rng.choice(("4", "51", "52", "53", "54", "55"))
        body += "".join(rng.choice(string.digits) for _ in range(15 - len(body)))
        number = body + luhn_digit(body)
        return " ".join(number[i:i + 4] for i in range(0, 16, 4)) if rng.random() < 0.6 else number
    if kind == "bank_account":
        if rng.random() < 0.6:
            return f"IBAN {iban(rng)}"
        return f"account number {rng.randint(10000000, 999999999999)} (routing number {aba_routing(rng)})"
    if kind == "ip_address":
        if rng.random() < 0.85:
            return ".".join(str(x) for x in (rng.randint(11, 223), rng.randint(0, 255), rng.randint(0, 255), rng.randint(1, 254)))
        return ":".join(f"{rng.randint(0, 65535):x}" for _ in range(8))
    raise ValueError(kind)


