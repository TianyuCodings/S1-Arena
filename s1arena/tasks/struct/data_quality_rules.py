class Bands(Rule):
    kind = "bands"

    def __init__(self, table, score, grade, bands):
        self.tables, self.score, self.grade, self.bands = (table,), score, grade, bands  # [(letter, low)] high to low
        parts = []
        for k, (letter, low) in enumerate(bands):
            high = 100 if k == 0 else bands[k - 1][1] - 1
            parts.append(f"{letter} for {low}-{high}" if low > 0 else f"{letter} below {bands[k - 1][1]}")
        self.text = f"{grade} must match {score}: " + ", ".join(parts) + "."

    def letter(self, score):
        """The band of a whole-number score; None when no band contains it (above 100 or not whole)."""
        if score is None or score != int(score) or score > 100:
            return None
        return next((letter for letter, low in self.bands[:-1] if score >= low), self.bands[-1][0])

    def ok(self, t):
        return all(r[self.grade] == self.letter(num(r[self.score])) for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        row = rng.choice(t[self.tables[0]].rows)
        letters = [b[0] for b in self.bands]
        k = letters.index(row[self.grade])
        row[self.grade] = letters[k + 1] if k + 1 < len(letters) and (k == 0 or rng.random() < 0.5) else letters[k - 1]


class Threshold(Rule):
    kind = "threshold"

    def __init__(self, table, col, limit, flag, below, other):
        self.tables, self.col, self.limit, self.flag, self.below, self.other = (table,), col, limit, flag, below, other
        self.text = f"{flag} must be '{below}' exactly when {col} is below {limit:.2f}, and '{other}' otherwise."

    def ok(self, t):
        return all(r[self.flag] == (self.below if num(r[self.col]) < self.limit else self.other) for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        row = rng.choice(t[self.tables[0]].rows)
        if rng.random() < 0.5:
            row[self.flag] = self.other if row[self.flag] == self.below else self.below
        else:
            below = row[self.flag] == self.below
            row[self.col] = f"{self.limit + (0.01 if below else -0.01) * rng.randint(1, 5):.2f}"


class NightsBetween(Rule):
    kind = "derived_days"

    def __init__(self, table, start, end, days):
        self.tables, self.start, self.end, self.days = (table,), start, end, days
        self.text = f"{days} must equal the number of days from {start} to {end}."

