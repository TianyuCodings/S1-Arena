class ZeroStock(Rule):
    kind = "conditional_value"
    tables = ("inventory",)
    text = "If discontinued is 'yes', stock_qty must be 0."

    def ok(self, t):
        return all(r["stock_qty"] == "0" for r in t["inventory"].rows if r["discontinued"] == "yes")

    def inject(self, t, rng):
        rows = [r for r in t["inventory"].rows if r["discontinued"] == "yes"] or t["inventory"].rows
        row = rng.choice(rows)
        row["discontinued"], row["stock_qty"] = "yes", str(rng.randint(1, 30))


