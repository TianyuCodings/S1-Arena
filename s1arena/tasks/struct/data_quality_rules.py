def parse_constraints(text: str) -> list[tuple[tuple[str, ...], str]]:
    """'t1&t2&EQ(t1.A,t2.A)&EQ(t1.B,t2.B)&IQ(t1.C,t2.C)' -> (('A', 'B'), 'C'): rows equal on A and B must be equal on C."""
    out = []
    for line in text.splitlines():
        eq = tuple(re.findall(r"EQ\(t1\.(\w+),t2\.\1\)", line))
        iq = re.findall(r"IQ\(t1\.(\w+),t2\.\1\)", line)
        if eq and len(iq) == 1 and (eq, iq[0]) != (("MeasureCode",), "Stateavg"):  # fails on the clean data too
            out.append((eq, iq[0]))
    return out


def fd_text(lhs: tuple[str, ...], rhs: str) -> str:
    same = " and the same ".join(lhs)
    return f"Any two rows that have the same {same} must also have the same {rhs}."


def fd_holds(rows, lhs, rhs) -> bool:
    seen = {}
    for r in rows:
        if seen.setdefault(tuple(r[c] for c in lhs), r[rhs]) != r[rhs]:
            return False
    return True


def fd_tested(rows, lhs) -> bool:
    """At least two rows share a left-hand side, so the rule is not satisfied vacuously."""
    keys = [tuple(r[c] for c in lhs) for r in rows]
    return len(set(keys)) < len(keys)


