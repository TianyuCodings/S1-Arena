# ---------- tables ----------

class Table:
    def __init__(self, name: str, columns: list[str], rows: list[dict[str, str]]):
        self.name, self.columns, self.rows = name, columns, rows

    def csv(self) -> str:
        buf = io.StringIO()
        writer = csv.writer(buf, lineterminator="\n")
        writer.writerow(self.columns)
        for row in self.rows:
            writer.writerow([row[c] for c in self.columns])
        return buf.getvalue().rstrip("\n")

    def copy(self) -> "Table":
        return Table(self.name, list(self.columns), [dict(r) for r in self.rows])


def pick_two_apart(rng, n):
    """Two row indices at least two rows apart (a duplicate should not sit next to its original)."""
    while True:
        i, j = sorted(rng.sample(range(n), 2))
        if j - i >= 2:
            return (i, j) if rng.random() < 0.5 else (j, i)


