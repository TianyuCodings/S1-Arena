@register_task
class GeneratedRules(TaskAdapter):
    name = f"{LEAF}/generated"
    leaf = LEAF
    source = "Data-quality rules over generated tables (generated)"
    url = REPO
    license = GENERATED
    tier = "C"
    criteria_source = "Written; gold from a deterministic rule checker"
    notes = ("Eight table types and 25 rule types (uniqueness, ranges, formats, allowed values, cross-column and cross-table "
             "constraints, conditional rules, arithmetic, functional dependencies, ordering, running balances). About half "
             "of the questions are violated, each by one or two small changes to otherwise clean rows; questions whose "
             "answers would interact are not asked together.")

    def load(self):
        return [self.make(i) for i in range(POOL)]

    def make(self, i: int) -> dict:
        rng = random.Random(f"{self.name}:{i}")
        domain = sorted(DOMAINS)[i % len(DOMAINS)]
        for _ in range(200):
            tables, rules = DOMAINS[domain](rng, rng.randint(12, 30))
            if not all(r.ok(tables) for r in rules):
                continue  # a clean table must satisfy every rule of its domain
            chosen = rng.sample(rules, RULES_PER_ITEM)
            target = [rng.random() < 0.5 for _ in chosen]  # True = violated
            if any(isinstance(r, (Pattern, Range, Decimals, Enum, NotEmpty)) and bad and any(re.search(rf"\b{r.col}\b", o.text) for o in chosen if o is not r)
                   for r, bad in zip(chosen, target)):
                continue  # a malformed or out-of-range value could make another question on the same column ambiguous
            try:
                for rule, bad in zip(chosen, target):
                    if bad:
                        for _ in range(1 if rng.random() < 0.75 else 2):
                            rule.inject(tables, rng)
            except (IndexError, ValueError):  # no row the injection could use; draw again
                continue
            labels = [not r.ok(tables) for r in chosen]
            if labels == target:  # an injection must not change the answer of another question
                return {"domain": domain, "tables": {k: v.csv() for k, v in tables.items()},
                        "rules": [(question_text(r), r.kind, "false" if bad else "true") for r, bad in zip(chosen, labels)]}
        raise RuntimeError(f"could not generate item {i}")

    def label_of(self, record):
        return f"{record['domain']}|{sum(g == 'false' for _, _, g in record['rules'])}"

    def to_item(self, record, rng):
        questions = {f"rule_{k + 1}": Question(type="boolean", instructions=text) for k, (text, _, _) in enumerate(record["rules"])}
        gold = {f"rule_{k + 1}": Gold(label=g) for k, (_, _, g) in enumerate(record["rules"])}
        return self.item(dict(record["tables"]), questions, gold, domain=record["domain"], rule_kinds=[kind for _, kind, _ in record["rules"]])


