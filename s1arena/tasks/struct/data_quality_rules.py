class Product(Rule):
    kind = "product"

    def __init__(self, table, total, a, b):
        self.tables, self.total, self.a, self.b = (table,), total, a, b
        self.text = f"In every row, {total} must equal {a} × {b}, rounded to the cent."

    def ok(self, t):
        for r in t[self.tables[0]].rows:
            x, y, z = num(r[self.a]), num(r[self.b]), num(r[self.total])
            if None in (x, y, z) or abs(round(x * y + 1e-9, 2) - z) > 0.001:
                return False
        return True

    def inject(self, t, rng):
        row = rng.choice(t[self.tables[0]].rows)
        z = num(row[self.total])
        delta = rng.choice([0.01, 0.1, 1.0, 10.0]) * rng.choice([-1, 1]) * rng.randint(1, 9)
        if z + delta <= 0:
            delta = abs(delta)
        row[self.total] = money(z + delta)


class FunctionalDependency(Rule):
    kind = "functional_dependency"

    def __init__(self, table, x, y):
        self.tables, self.x, self.y = (table,), x, y
        self.text = f"Rows that have the same non-empty {x} must have the same {y}."

    def ok(self, t):
        seen = {}
        for r in t[self.tables[0]].rows:
            if r[self.x] and seen.setdefault(r[self.x], r[self.y]) != r[self.y]:
                return False
        return True

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        groups = defaultdict(list)
        for r in rows:
            if r[self.x]:
                groups[r[self.x]].append(r)
        group = rng.choice([g for k, g in sorted(groups.items()) if len(g) >= 2])
        others = sorted({r[self.y] for r in rows} - {group[0][self.y]})
        rng.choice(group)[self.y] = rng.choice(others)


class Reference(Rule):
    kind = "reference"

    def __init__(self, child, fk, parent, pk, new_value):
        self.tables, self.fk, self.pk, self.new_value = (child, parent), fk, pk, new_value
        self.text = f"Every {fk} in the {child} table must match a {pk} in the {parent} table."

    def ok(self, t):
        keys = {r[self.pk] for r in t[self.tables[1]].rows}
        return all(r[self.fk] in keys for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        keys = {r[self.pk] for r in t[self.tables[1]].rows}
        rng.choice(t[self.tables[0]].rows)[self.fk] = self.new_value(keys, rng)


class SelfReference(Rule):
    kind = "self_reference"

    def __init__(self, table, fk, pk, new_value):
        self.tables, self.fk, self.pk, self.new_value = (table,), fk, pk, new_value
        self.text = f"Every non-empty {fk} must be the {pk} of a different row in the same table."

    def ok(self, t):
        rows = t[self.tables[0]].rows
        return all(any(other[self.pk] == r[self.fk] for other in rows if other is not r) for r in rows if r[self.fk])

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        row = rng.choice([r for r in rows if r[self.fk]])
        keys = {r[self.pk] for r in rows}
        row[self.fk] = row[self.pk] if rng.random() < 0.4 else self.new_value(keys, rng)


class Increasing(Rule):
    kind = "increasing"

    def __init__(self, table, col, parse):
        self.tables, self.col, self.parse = (table,), col, parse
        self.text = f"The rows must be in strictly increasing order of {col}."

    def ok(self, t):
        values = [self.parse(r[self.col]) for r in t[self.tables[0]].rows]
        return all(a is not None and b is not None and a < b for a, b in zip(values, values[1:]))

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        i = rng.randrange(len(rows) - 1)
        rows[i][self.col], rows[i + 1][self.col] = rows[i + 1][self.col], rows[i][self.col]


class MaxGap(Rule):
    kind = "max_gap"

    def __init__(self, table, col, minutes):
        self.tables, self.col, self.minutes = (table,), col, minutes
        self.text = f"Consecutive rows must be at most {minutes} minutes apart in {col}."

    def ok(self, t):
        values = [parse_time(r[self.col]) for r in t[self.tables[0]].rows]
        return all(a and b and abs(b - a) <= dt.timedelta(minutes=self.minutes) for a, b in zip(values, values[1:]))

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        i = rng.randrange(1, len(rows))
        gap = parse_time(rows[i][self.col]) - parse_time(rows[i - 1][self.col])
        shift = dt.timedelta(minutes=self.minutes + rng.randint(1, 9)) - gap
        for row in rows[i:]:
            row[self.col] = (parse_time(row[self.col]) + shift).isoformat(sep=" ", timespec="minutes")


