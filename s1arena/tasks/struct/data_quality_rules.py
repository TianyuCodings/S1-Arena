class RunningBalance(Rule):
    kind = "running_balance"

    def __init__(self, table, kind_col, amount, balance):
        self.tables, self.kind_col, self.amount, self.balance = (table,), kind_col, amount, balance
        self.text = (f"From the second row on, {balance} must equal the previous row's {balance} plus {amount} when "
                     f"{kind_col} is 'credit', or minus {amount} when it is 'debit'.")

    def ok(self, t):
        rows = t[self.tables[0]].rows
        for prev, row in zip(rows, rows[1:]):
            sign = {"credit": 1, "debit": -1}.get(row[self.kind_col])
            if sign is None or abs(float(prev[self.balance]) + sign * float(row[self.amount]) - float(row[self.balance])) > 0.001:
                return False
        return True

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        row = rng.choice(rows[1:])
        row[self.balance] = money(float(row[self.balance]) + rng.choice([-1, 1]) * rng.choice([0.01, 0.1, 1, 10, 100]) * rng.randint(1, 9))


class CrossDate(Rule):
    kind = "cross_table_date"

    def __init__(self, child, fk, date, parent, pk, parent_date):
        self.tables, self.fk, self.date, self.pk, self.parent_date = (child, parent), fk, date, pk, parent_date
        self.text = f"Each {date} in the {child} table must not be earlier than the {parent_date} of the matching {pk} in the {parent} table."

    def ok(self, t):
        start = {r[self.pk]: parse_date(r[self.parent_date]) for r in t[self.tables[1]].rows}
        return all(r[self.fk] not in start or parse_date(r[self.date]) >= start[r[self.fk]] for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        start = {r[self.pk]: parse_date(r[self.parent_date]) for r in t[self.tables[1]].rows}
        row = rng.choice([r for r in t[self.tables[0]].rows if r[self.fk] in start])
        row[self.date] = iso(start[row[self.fk]] - dt.timedelta(days=rng.randint(1, 20)))


