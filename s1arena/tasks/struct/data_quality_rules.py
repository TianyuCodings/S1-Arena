# Every rule has .text, .tables (names it reads), .ok(tables) -> bool and .inject(tables, rng) -> None.

class Rule:
    kind = ""
    tables: tuple[str, ...] = ()

    def ok(self, t) -> bool:
        raise NotImplementedError

    def inject(self, t, rng) -> None:
        raise NotImplementedError


class Unique(Rule):
    kind = "unique"

    def __init__(self, table, col):
        self.tables, self.col = (table,), col
        self.text = f"Values in column {col} must be unique: no value may appear in more than one row."

    def ok(self, t):
        values = [r[self.col] for r in t[self.tables[0]].rows]
        return len(values) == len(set(values))

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        i, j = pick_two_apart(rng, len(rows))
        rows[j][self.col] = rows[i][self.col]


class UniquePair(Rule):
    kind = "unique_pair"

    def __init__(self, table, a, b):
        self.tables, self.a, self.b = (table,), a, b
        self.text = f"No two rows may have the same combination of {a} and {b}."

    def ok(self, t):
        pairs = [(r[self.a], r[self.b]) for r in t[self.tables[0]].rows]
        return len(pairs) == len(set(pairs))

    def inject(self, t, rng):
        rows = t[self.tables[0]].rows
        i, j = pick_two_apart(rng, len(rows))
        rows[j][self.a], rows[j][self.b] = rows[i][self.a], rows[i][self.b]


class NotEmpty(Rule):
    kind = "not_empty"

    def __init__(self, table, col):
        self.tables, self.col = (table,), col
        self.text = f"Column {col} must not be empty in any row."

    def ok(self, t):
        return all(r[self.col].strip() for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        rng.choice(t[self.tables[0]].rows)[self.col] = ""


class Range(Rule):
    kind = "range"

    def __init__(self, table, col, lo, hi, decimals=0, whole=False):
        self.tables, self.col, self.lo, self.hi, self.decimals, self.whole = (table,), col, lo, hi, decimals, whole
        fmt = lambda v: f"{v:,.{decimals}f}"
        if whole:
            self.text = f"Every value of {col} must be a whole number from {fmt(lo)} to {fmt(hi)}."
        else:
            self.text = f"Every value of {col} must be a number from {fmt(lo)} to {fmt(hi)} (inclusive)."

    def ok(self, t):
        for r in t[self.tables[0]].rows:
            v = num(r[self.col])
            if v is None or not self.lo <= v <= self.hi:
                return False
            if self.whole and not re.fullmatch(r"-?\d+", r[self.col]):
                return False
        return True

    def inject(self, t, rng):
        row = rng.choice(t[self.tables[0]].rows)
        step = 10 ** -self.decimals
        options = [self.hi + step * rng.randint(1, 3), self.lo - step * rng.randint(1, 3)]
        if self.whole:
            options.append(rng.randint(int(self.lo), int(self.hi) - 1) + 0.5)
            value = rng.choice(options)
            row[self.col] = f"{value:.1f}" if value % 1 else f"{value:.0f}"
        else:
            row[self.col] = f"{rng.choice(options):.{self.decimals}f}"


class Pattern(Rule):
    kind = "pattern"

    def __init__(self, table, col, regex, description, mutators, optional=False):
        self.tables, self.col, self.regex, self.mutators, self.optional = (table,), col, re.compile(regex), mutators, optional
        self.text = f"Every {'non-empty ' if optional else ''}value of {col} must be {description}."

    def ok(self, t):
        return all(self.regex.fullmatch(r[self.col]) for r in t[self.tables[0]].rows if r[self.col] or not self.optional)

    def inject(self, t, rng):
        rows = [r for r in t[self.tables[0]].rows if r[self.col]]
        for _ in range(50):
            row = rng.choice(rows)
            bad = rng.choice(self.mutators)(row[self.col], rng)
            if bad and not self.regex.fullmatch(bad):
                row[self.col] = bad
                return


class Enum(Rule):
    kind = "enum"

    def __init__(self, table, col, allowed, variants):
        self.tables, self.col, self.allowed, self.variants = (table,), col, allowed, variants
        self.text = f"{col} may only take one of these values: {', '.join(allowed)}."

    def ok(self, t):
        return all(r[self.col] in self.allowed for r in t[self.tables[0]].rows)

    def inject(self, t, rng):
        row = rng.choice(t[self.tables[0]].rows)
        value = row[self.col]
        options = [v for v in self.variants.get(value, []) if v not in self.allowed] + [value.capitalize() if value.islower() else value.lower()]
        row[self.col] = rng.choice([o for o in options if o not in self.allowed])


class Compare(Rule):
    """a OP b within a row, for dates, datetimes or numbers; rows with an empty a or b are skipped."""

    kind = "compare"
    WORDS = {
        ("date", ">="): "must not be earlier than", ("date", ">"): "must be later than",
        ("time", ">"): "must be later than", ("num", "<"): "must be less than", ("num", "<="): "must not exceed",
    }

    def __init__(self, table, a, op, b, kind):
        self.tables, self.a, self.op, self.b, self.vkind = (table,), a, op, b, kind
        self.text = f"In every row where both are filled in, {a} {self.WORDS[(kind, op)]} {b}."

    def value(self, text):
        return {"date": parse_date, "time": parse_time, "num": num}[self.vkind](text) if text else None

    def ok(self, t):
        for r in t[self.tables[0]].rows:
            a, b = self.value(r[self.a]), self.value(r[self.b])
            if a is None or b is None:
                continue
            if not {"<": a < b, "<=": a <= b, ">": a > b, ">=": a >= b}[self.op]:
                return False
        return True

    def inject(self, t, rng):
        rows = [r for r in t[self.tables[0]].rows if r[self.a] and r[self.b]]
        row = rng.choice(rows)
        b = self.value(row[self.b])
        if self.vkind == "date":
            back = rng.randint(0 if self.op == ">" else 1, 3)
            row[self.a] = iso(b - dt.timedelta(days=back))
        elif self.vkind == "time":
            row[self.a] = (b - dt.timedelta(minutes=rng.choice([0, 5, 15, 30, 60]))).isoformat(sep=" ", timespec="minutes")
        else:
            bump = 0.0 if self.op == "<" else 0.01 * rng.randint(1, 50)
            row[self.a] = money(b + bump)


