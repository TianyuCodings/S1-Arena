"""Leaf: action safety (动作安全性): will this action cause injury, damage or a collision?

- ASIMOV 2.0 injuries (Google DeepMind, 2025): scenarios built from real hospital injury reports
  (NEISS) with a robot instruction; the effect of carrying out the instruction on the chance of
  injury (eliminates, reduces, no change, increases) as rated by human raters. The scenario
  texts were written by Gemini from the reports; the labels are human.
- SafeText (Levy et al., EMNLP 2022): everyday situations with pieces of advice that are safe or
  would lead to physical harm, collected from Reddit and filtered and written by crowdworkers.
- Robot moves in a floor plan (generated): will a sequence of drive commands make the robot
  hit a wall, a piece of furniture or a person? Gold by simulation, checked independently.
"""

