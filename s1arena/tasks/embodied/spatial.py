"""Leaf: spatial and trajectory reasoning (空间 / 轨迹推理), text-only.

ERQA and similar embodied spatial benchmarks are image-based and belong to the multimodal
track; here the scenes are given in text:
- StepGame: relations between agents on a grid, stated in story sentences with distractors,
  1 to 10 reasoning hops; nine relation labels produced by the generator;
- SpatialEval (text-only split): object relations on a described map, and navigation in an
  ASCII maze along a marked route (turn counts and where the exit lies);
- LLM-BabyBench Predict: where a BabyAI agent ends up, and facing which way, after a sequence
  of turns, moves and object actions in a described grid world; gold is the BabyAI
  simulator's final state.
"""

from __future__ import annotations

import json
import re

from ...env import load_env
from ...registry import register_task
from ...schema import Gold, Question
from ..base import TaskAdapter

LEAF = "embodied/spatial_reasoning"


def hf_file(repo: str, path: str, rev: str) -> str:
    load_env()
    from huggingface_hub import hf_hub_download

    return hf_hub_download(repo, path, repo_type="dataset", revision=rev)


# ---------- StepGame ----------

RELATIONS = {  # StepGame's nine labels, in a fixed natural order
    "left": "left: directly to the left", "right": "right: directly to the right", "above": "above: directly above",
    "below": "below: directly below", "upper-left": "upper-left: above and to the left", "upper-right": "upper-right: above and to the right",
    "lower-left": "lower-left: below and to the left", "lower-right": "lower-right: below and to the right",
    "overlap": "overlap: at the same position",
}


@register_task
class StepGame(TaskAdapter):
    name = f"{LEAF}/stepgame"
    leaf = LEAF
    source = "StepGame, test set with distracting statements (Shi et al., AAAI 2022; regenerated February 2024)"
    url = "https://huggingface.co/datasets/michaelszx/StepGame"
    license = "MIT"
    tier = "B"
    criteria_source = "StepGame question verbatim (in the state); options are its nine relation labels with a short gloss"
    notes = ("Stories place agents on a 2-D grid with relations phrased in many ways (clock positions, diagonals, 'on top of'), "
             "including statements irrelevant to the question; 1 to 10 reasoning hops, in equal shares. Labels come from the "
             "generator. The release used here fixed template typos found in the original data.")

    def load(self):
        rows = []
        with open(hf_file("michaelszx/StepGame", "test.jsonl", "6d859381dfd518cae3f073b268aaa323bf4dcf04"), encoding="utf-8") as f:
            for i, line in enumerate(f):
                r = json.loads(line)
                rows.append({"i": i, "story": r["story"], "question": r["question"], "label": r["label"], "hops": int(r["k_hop"])})
        return rows

    def label_of(self, record):
        return str(record["hops"])

    def to_item(self, record, rng):
        question = Question(type="choice", criteria=dict(RELATIONS), instructions=(
            "The story places agents on a 2-D grid. Answer the question: what is the position of the first agent named in the "
            "question relative to the second one?"))
        state = {"story": " ".join(s.strip() for s in record["story"]), "question": record["question"]}
        return self.item(state, {"relation": question}, {"relation": Gold(label=record["label"])}, hops=record["hops"], original_index=record["i"])


# ---------- SpatialEval (text-only) ----------

@register_task
class SpatialEvalText(TaskAdapter):
    name = f"{LEAF}/spatialeval"
    leaf = LEAF
    source = "SpatialEval text-only split, Spatial-Map and Maze-Nav tasks (Wang et al., NeurIPS 2024)"
    url = "https://huggingface.co/datasets/MilaWang/SpatialEval"
    license = "Not stated"
    tier = "A"
    criteria_source = "SpatialEval questions and answer options verbatim; the description is moved into the state"
    notes = ("Spatial-Map: directions between named places on a described map; Maze-Nav: an ASCII maze with the route from S to E "
             "marked, asking for the number of turns or where the exit lies. Both are generated by program. Spatial-Grid "
             "(counting animals) and Spatial-Real are not used. The dataset states no license.")

    def load(self):
        import pandas as pd

        df = pd.read_parquet(hf_file("MilaWang/SpatialEval", "tqa/test-00000-of-00001.parquet", "59ce0450bf65ae8dfa3590062442cf642474d7fe"))
        rows = []
        for r in df.to_dict("records"):
            task = r["id"].split(".")[0]
            if task not in ("spatialmap", "mazenav"):
                continue
            text = r["text"]
            cut = text.index("Please answer the following")
            context, rest = text[:cut].strip(), text[cut:]
            question = re.sub(r"^Please answer the following (multiple-choice )?question based on the provided information\.\s*", "", rest)
            question, _, opts = question.partition("Available options:")
            options = dict(re.findall(r"^\s*([A-D])\. (.*?)\.?$", opts.strip(), re.M))
            if len(options) < 2 or r["oracle_option"] not in options:
                continue
            rows.append({"id": r["id"], "task": task, "context": context, "question": question.strip(), "options": options,
                         "answer": r["oracle_option"], "answer_text": r["oracle_answer"]})
        return rows

    def label_of(self, record):
        return f"{record['task']}|{record['answer']}"

    def to_item(self, record, rng):
        question = Question(type="choice", criteria=record["options"], instructions=record["question"])
        return self.item({"description": record["context"]}, {"answer": question}, {"answer": Gold(label=record["answer"])},
                         task_type=record["task"], original_id=record["id"])


# ---------- LLM-BabyBench Predict ----------

BABY_REPO, BABY_REV = "salem-mbzuai/LLM-BabyBench", "1115985644a1f6d626515f6929012c04827ba2f7"
DIRS = ("east", "south", "west", "north")  # BabyAI direction indices 0-3
STEP = ((1, 0), (0, 1), (-1, 0), (0, -1))
MAX_ACTIONS = 30


def parse_pose(text: str) -> tuple[int, int, int]:
    x, y, d = map(int, re.findall(r"-?\d+", text))
    return x, y, d


def dead_reckoning(start: tuple[int, int, int], actions: list[str], swap_turns: bool = False) -> tuple[int, int, int]:
    """Final pose if every forward move succeeded (walls, doors and objects ignored)."""
    x, y, d = start
    for a in actions:
        if a in ("left", "right"):
            turn = -1 if (a == "left") != swap_turns else 1
            d = (d + turn) % 4
        elif a == "forward":
            x, y = x + STEP[d][0], y + STEP[d][1]
    return x, y, d


def pose_text(p: tuple[int, int, int]) -> str:
    return f"at ({p[0]}, {p[1]}), facing {DIRS[p[2]]}"


@register_task
class BabyBenchPredict(TaskAdapter):
    name = f"{LEAF}/babybench_predict"
    leaf = LEAF
    source = "LLM-BabyBench Predict: final agent pose after an action sequence in BabyAI grid worlds (2025)"
    url = "https://huggingface.co/datasets/salem-mbzuai/LLM-BabyBench"
    license = "MIT"
    tier = "B"
    criteria_source = "LLM-BabyBench environment description verbatim; question adapted from its Predict task; the three wrong options are generated"
    notes = ("Sequences of at most 30 actions over 16 BabyAI levels. Gold is the simulator's final position and heading. The "
             "sequences come from BabyAI's own bot, so no move is ever blocked; the task is to track position and heading through "
             "turns and moves. The three wrong options come from typical mistakes: left and right turns confused, the right cell "
             "with the wrong heading, and one cell off.")

    def load(self):
        import pandas as pd

        df = pd.read_csv(hf_file(BABY_REPO, "predict/LLM_BABYBENCH_Predict.csv", BABY_REV))
        rows = []
        for r in df.to_dict("records"):
            actions = [a.strip() for a in str(r["action_sequence"]).split(",") if a.strip()]
            if not actions or len(actions) > MAX_ACTIONS:
                continue
            start, target = parse_pose(r["initial_state"]), parse_pose(r["target_state"])
            rows.append({"level": r["level_name"], "seed": int(r["seed"]), "env": r["env_description"].strip(), "actions": actions,
                         "start": list(start), "target": list(target)})
        return rows

    def label_of(self, record):
        return record["level"]

    def to_item(self, record, rng):
        start, target = tuple(record["start"]), tuple(record["target"])
        candidates = [dead_reckoning(start, record["actions"]), dead_reckoning(start, record["actions"], swap_turns=True),
                      (target[0], target[1], (target[2] + 2) % 4), (target[0], target[1], (target[2] + rng.choice((1, 3))) % 4),
                      (target[0] + STEP[target[2]][0], target[1] + STEP[target[2]][1], target[2]),
                      (target[0] - STEP[target[2]][0], target[1] - STEP[target[2]][1], target[2])]
        wrong = []
        for c in candidates:
            if c != target and c not in wrong:
                wrong.append(c)
        poses = [target] + rng.sample(wrong, 3)
        rng.shuffle(poses)
        options = {f"pose_{i + 1}": pose_text(p) for i, p in enumerate(poses)}
        gold = f"pose_{poses.index(target) + 1}"
        question = Question(type="choice", criteria=options, instructions=(
            "The agent carries out the actions below in order, starting from its initial position and facing direction. Where "
            "is it at the end, and which way does it face?"))
        state = {"environment": record["env"], "actions": ", ".join(record["actions"])}
        return self.item(state, {"final_pose": question}, {"final_pose": Gold(label=gold)}, level=record["level"], seed=record["seed"])
