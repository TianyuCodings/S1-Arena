"""Leaf: logic puzzles (益智).

Generated positions from three classic single-player puzzles, with answers computed by exact
solvers: Sudoku (does the grid break a rule; can it still be completed), the 8-puzzle (which
tile to slide first on a shortest solution, from a breadth-first search over all 181,440
positions) and Minesweeper (is a covered square certainly safe, certainly a mine, or
undetermined, from an exhaustive search over the mine layouts consistent with the numbers
and the mine count). Pools are seeded by task name, so every build produces the same items;
an independent checker re-derives every answer.
"""

