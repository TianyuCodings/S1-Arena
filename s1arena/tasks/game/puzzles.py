# ---------- Sudoku ----------

def _peers() -> list[set[int]]:
    peers = []
    for i in range(81):
        r, c = divmod(i, 9)
        box = {(r // 3 * 3 + dr) * 9 + (c // 3 * 3 + dc) for dr in range(3) for dc in range(3)}
        peers.append(({r * 9 + k for k in range(9)} | {k * 9 + c for k in range(9)} | box) - {i})
    return peers


PEERS = _peers()


def random_solution(rng: random.Random) -> list[int]:
    """A random complete Sudoku grid (randomized backtracking)."""
    grid = [0] * 81

    def fill(i: int) -> bool:
        if i == 81:
            return True
        digits = list(range(1, 10))
        rng.shuffle(digits)
        used = {grid[p] for p in PEERS[i]}
        for d in digits:
            if d not in used:
                grid[i] = d
                if fill(i + 1):
                    return True
        grid[i] = 0
        return False

    fill(0)
    return grid


def conflicts(grid: list[int]) -> list[tuple[int, int]]:
    """Pairs of filled squares in the same row, column or box that hold the same digit."""
    return [(i, p) for i in range(81) if grid[i] for p in PEERS[i] if p > i and grid[p] == grid[i]]


def count_solutions(grid: list[int], limit: int = 1) -> int:
    """Number of completions (up to limit), by backtracking on the square with the fewest candidates."""
    if conflicts(grid):
        return 0
    g = list(grid)

    def search() -> int:
        best, best_cands = None, None
        for i in range(81):
            if g[i] == 0:
                cands = [d for d in range(1, 10) if all(g[p] != d for p in PEERS[i])]
                if not cands:
                    return 0
                if best is None or len(cands) < len(best_cands):
                    best, best_cands = i, cands
                    if len(cands) == 1:
                        break
        if best is None:
            return 1
        found = 0
        for d in best_cands:
            g[best] = d
            found += search()
            if found >= limit:
                break
        g[best] = 0
        return found

    return search()


def render_sudoku(grid: list[int]) -> str:
    lines = []
    for r in range(9):
        if r in (3, 6):
            lines.append("------+-------+------")
        cells = ["." if grid[r * 9 + c] == 0 else str(grid[r * 9 + c]) for c in range(9)]
        lines.append(" ".join(cells[0:3]) + " | " + " ".join(cells[3:6]) + " | " + " ".join(cells[6:9]))
    return "\n".join(lines)


SUDOKU_RULES = ("In Sudoku, each row, each column and each of the nine 3x3 boxes must end up holding the digits 1 to 9 exactly "
                "once. '.' marks an empty square.")


@register_task
class Sudoku(Generated):
    name = f"{LEAF}/sudoku"
    source = "Sudoku grids: rule check and completability (generated)"
    criteria_source = "Written; gold is computed by a rule checker and an exhaustive solver"
    notes = ("Two kinds of grids. Rule check: 22-60 digits of a random solved grid, in half of them one digit changed so that it "
             "repeats in its row, column or box, and in a quarter of the rest one digit changed without creating a repeat (still "
             "valid). Completability: 24-36 digits of a random solved grid, in about half of them one digit changed to another "
             "that repeats nowhere; an exhaustive solver decides whether any completion exists. Checked by an independent "
             "checker and a second solver.")

    POOL = 2400

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows = []
        for i in range(self.POOL):
            kind = ("rule_check", "completable")[i % 2]
            want = ("true", "false")[(i // 2) % 2]
            while True:
                row = self._make(rng, kind)
                if row["label"] == want:
                    break
            rows.append(row)
        return rows

    def _make(self, rng: random.Random, kind: str) -> dict:
        solution = random_solution(rng)
        if kind == "rule_check":
            shown = rng.sample(range(81), rng.randint(22, 60))
            grid = [solution[i] if i in shown else 0 for i in range(81)]
            change = rng.random()
            if change < 0.5:  # introduce a repeat in a row, column or box
                unit = rng.choice(("row", "column", "box"))
                i = rng.choice(shown)
                r, c = divmod(i, 9)
                same = {"row": lambda p: p // 9 == r, "column": lambda p: p % 9 == c,
                        "box": lambda p: (p // 27, p % 9 // 3) == (r // 3, c // 3)}[unit]
                others = [p for p in shown if p != i and same(p)]
                if not others:
                    return {"label": None}
                grid[i] = grid[rng.choice(others)]
            elif change < 0.625:  # change a digit without creating a repeat
                i = rng.choice(shown)
                options = [d for d in range(1, 10) if d != grid[i] and all(grid[p] != d for p in PEERS[i])]
                if not options:
                    return {"label": None}
                grid[i] = rng.choice(options)
            label = "false" if conflicts(grid) else "true"
            return {"kind": kind, "grid": "".join(map(str, grid)), "label": label, "givens": len(shown)}
        shown = rng.sample(range(81), rng.randint(24, 36))
        grid = [solution[i] if i in shown else 0 for i in range(81)]
        if rng.random() < 0.6:
            i = rng.choice(shown)
            options = [d for d in range(1, 10) if d != grid[i] and all(grid[p] != d for p in PEERS[i])]
            if not options:
                return {"label": None}
            grid[i] = rng.choice(options)
        label = "true" if count_solutions(grid) > 0 else "false"
        return {"kind": kind, "grid": "".join(map(str, grid)), "label": label, "givens": len(shown)}

    def label_of(self, record):
        return f"{record['kind']}|{record['label']}"

    def to_item(self, record, rng):
        grid = [int(ch) for ch in record["grid"]]
        if record["kind"] == "rule_check":
            text = (f"{SUDOKU_RULES} Does this partly filled grid follow the rules so far, that is, does no digit appear twice in "
                    "any row, column or 3x3 box? Empty squares are ignored, and the grid need not be solvable.")
        else:
            text = (f"{SUDOKU_RULES} Can this grid be completed: can the empty squares be filled so that the finished grid "
                    "follows the rules, keeping every digit already shown?")
        question = Question(type="boolean", instructions=text)
        return self.item({"grid": render_sudoku(grid)}, {record["kind"]: question}, {record["kind"]: Gold(label=record["label"])},
                         kind=record["kind"], givens=record["givens"])


# ---------- 8-puzzle ----------

GOAL = (1, 2, 3, 4, 5, 6, 7, 8, 0)
DIRECTION = {3: "down", -3: "up", 1: "right", -1: "left"}  # blank index minus tile index -> direction the tile moves


def neighbours(state: tuple) -> list[tuple[int, tuple]]:
    """(tile that slides, resulting state) for every legal move."""
    b = state.index(0)
    r, c = divmod(b, 3)
    out = []
    for t in (b - 3 if r > 0 else None, b + 3 if r < 2 else None, b - 1 if c > 0 else None, b + 1 if c < 2 else None):
        if t is None:
            continue
        s = list(state)
        s[b], s[t] = s[t], 0
        out.append((state[t], tuple(s)))
    return out


@functools.lru_cache(maxsize=1)
def distances() -> dict[tuple, int]:
    """Breadth-first search from the goal over all reachable positions (181,440)."""
    dist = {GOAL: 0}
    queue = deque([GOAL])
    while queue:
        s = queue.popleft()
        for _, t in neighbours(s):
            if t not in dist:
                dist[t] = dist[s] + 1
                queue.append(t)
    return dist


def render_tiles(state: tuple) -> str:
    return "\n".join(" ".join(str(v) if v else "_" for v in state[r * 3: r * 3 + 3]) for r in range(3))


PUZZLE_BANDS = ((1, 6), (7, 12), (13, 18), (19, 24), (25, 31))


@register_task
class SlidingPuzzle(Generated):
    name = f"{LEAF}/sliding_puzzle"
    source = "8-puzzle positions with a unique best first move (generated)"
    criteria_source = "Written; gold comes from an exact breadth-first search over all positions"
    sampling = "balanced"
    notes = ("Only positions where exactly one move starts a shortest solution. Equal shares of five bands of solution length "
             "(1-6 to 25-31 moves). Checked by an independent A* search.")

    PER_BAND = 600

    def load(self):
        dist = distances()
        rng = random.Random(f"{self.name}:pool")
        by_band: dict[int, list] = {i: [] for i in range(len(PUZZLE_BANDS))}
        for state in sorted(dist):
            d = dist[state]
            if d == 0:
                continue
            best = [tile for tile, t in neighbours(state) if dist[t] == d - 1]
            if len(best) != 1:
                continue
            band = next(i for i, (lo, hi) in enumerate(PUZZLE_BANDS) if lo <= d <= hi)
            by_band[band].append({"state": list(state), "answer": best[0], "length": d, "band": band})
        rows = []
        for band, members in by_band.items():
            rng.shuffle(members)
            rows += members[: self.PER_BAND]
        return rows

    def label_of(self, record):
        lo, hi = PUZZLE_BANDS[record["band"]]
        return f"{lo}-{hi} moves"

    def to_item(self, record, rng):
        state = tuple(record["state"])
        blank = state.index(0)
        options = {}
        for tile, _ in sorted(neighbours(state)):
            options[str(tile)] = f"slide tile {tile} {DIRECTION[blank - state.index(tile)]} into the empty square"
        question = Question(type="choice", criteria=options, instructions=(
            "8-puzzle: a tile next to the empty square (_) can slide into it. The puzzle is solved when the tiles read 1 to 8 in "
            "order, row by row, with the empty square at the bottom right. Which move is the first step of a shortest solution?"))
        state_text = {"board": render_tiles(state), "goal": render_tiles(GOAL)}
        return self.item(state_text, {"first_move": question}, {"first_move": Gold(label=str(record["answer"]))},
                         solution_length=record["length"])


# ---------- Minesweeper ----------

ROWS, COLS, MINES = 9, 9, 10  # the Beginner board
ROW_NAMES = "ABCDEFGHI"
STATUS = {
    "safe": "Certainly safe: no arrangement of mines that fits the numbers and the mine count puts a mine there",
    "mine": "Certainly a mine: every arrangement that fits the numbers and the mine count puts a mine there",
    "unknown": "Cannot be determined: the numbers and the mine count allow both a mine and no mine there",
}


def around(i: int) -> list[int]:
    r, c = divmod(i, COLS)
    return [(r + dr) * COLS + c + dc for dr in (-1, 0, 1) for dc in (-1, 0, 1)
            if (dr or dc) and 0 <= r + dr < ROWS and 0 <= c + dc < COLS]


def reveal(start: int, mines: set[int], shown: set[int]) -> None:
    """Uncover a safe square; empty squares (no adjacent mine) uncover their neighbours too."""
    stack = [start]
    while stack:
        i = stack.pop()
        if i in shown:
            continue
        shown.add(i)
        if not any(n in mines for n in around(i)):
            stack += [n for n in around(i) if n not in shown]


def mine_status(shown: set[int], numbers: dict[int, int], total: int) -> dict[int, tuple[int, int]]:
    """For every covered square next to a number: (weight of layouts with a mine there, weight without).

    Layouts of the frontier are enumerated exactly; each is weighted by the number of ways to place
    the remaining mines on the covered squares that touch no number.
    """
    covered = [i for i in range(ROWS * COLS) if i not in shown]
    frontier = sorted({n for i in numbers for n in around(i) if n not in shown})
    free = len(covered) - len(frontier)
    index = {cell: k for k, cell in enumerate(frontier)}
    constraints = [([index[n] for n in around(i) if n in index], numbers[i]) for i in numbers]
    touching: list[list[int]] = [[] for _ in frontier]
    for ci, (cells, _) in enumerate(constraints):
        for k in cells:
            touching[k].append(ci)
    value = [None] * len(frontier)
    placed, open_left = [0] * len(constraints), [len(cells) for cells, _ in constraints]
    tally = {cell: [0, 0] for cell in frontier}

    def search(k: int, mines: int) -> None:
        if k == len(frontier):
            rest = total - mines
            if 0 <= rest <= free:
                w = math.comb(free, rest)
                for cell, v in zip(frontier, value):
                    tally[cell][0 if v else 1] += w
            return
        for v in (1, 0):
            ok = True
            for ci in touching[k]:
                need = constraints[ci][1] - placed[ci] - v
                if need < 0 or need > open_left[ci] - 1:
                    ok = False
                    break
            if not ok or mines + v > total:
                continue
            value[k] = v
            for ci in touching[k]:
                placed[ci] += v
                open_left[ci] -= 1
            search(k + 1, mines + v)
            for ci in touching[k]:
                placed[ci] -= v
                open_left[ci] += 1
        value[k] = None

    search(0, 0)
    return {cell: (w[0], w[1]) for cell, w in tally.items()}


def render_minefield(shown: set[int], numbers: dict[int, int]) -> str:
    lines = ["  " + " ".join(str(c + 1) for c in range(COLS))]
    for r in range(ROWS):
        cells = []
        for c in range(COLS):
            i = r * COLS + c
            cells.append("#" if i not in shown else "." if numbers.get(i, 0) == 0 else str(numbers[i]))
        lines.append(ROW_NAMES[r] + " " + " ".join(cells))
    return "\n".join(lines)


def square_name(i: int) -> str:
    return f"{ROW_NAMES[i // COLS]}{i % COLS + 1}"


@register_task
class Minesweeper(Generated):
    name = f"{LEAF}/minesweeper"
    source = "Minesweeper Beginner positions (9x9, 10 mines) with an exact deduction per square (generated)"
    criteria_source = "Written; gold is computed by exhaustive enumeration of the mine layouts consistent with the board"
    notes = ("Positions arise from a random first click (its neighbourhood is mine-free) plus 0-6 further random safe clicks. "
             "The question is about one covered square next to a number; the pool has equal thirds of certainly safe, certainly "
             "a mine and undetermined squares (for undetermined squares the exact mine probability is kept in the metadata). "
             "Positions whose frontier exceeds 24 squares are skipped. Checked by an independent solver.")

    POOL = 1800

    def load(self):
        rng = random.Random(f"{self.name}:pool")
        rows, wanted = [], ("safe", "mine", "unknown")
        while len(rows) < self.POOL:
            want = wanted[len(rows) % 3]
            row = self._make(rng, want)
            if row:
                rows.append(row)
        return rows

    def _make(self, rng: random.Random, want: str) -> dict | None:
        first = rng.randrange(ROWS * COLS)
        protected = set(around(first)) | {first}
        mines = set(rng.sample([i for i in range(ROWS * COLS) if i not in protected], MINES))
        shown: set[int] = set()
        reveal(first, mines, shown)
        for _ in range(rng.randint(0, 6)):
            safe = [i for i in range(ROWS * COLS) if i not in mines and i not in shown]
            if len(safe) <= 1:
                break
            reveal(rng.choice(safe), mines, shown)
        covered_safe = [i for i in range(ROWS * COLS) if i not in mines and i not in shown]
        if not covered_safe:
            return None  # the board is solved
        numbers = {i: sum(n in mines for n in around(i)) for i in shown}
        frontier_numbers = {i: v for i, v in numbers.items() if v > 0}
        frontier = {n for i in frontier_numbers for n in around(i) if n not in shown}
        if not frontier or len(frontier) > 24:
            return None
        tally = mine_status(shown, frontier_numbers, MINES)
        status = {cell: "mine" if w[1] == 0 else "safe" if w[0] == 0 else "unknown" for cell, w in tally.items()}
        choices = sorted(cell for cell, s in status.items() if s == want)
        if not choices:
            return None
        target = rng.choice(choices)
        w_mine, w_safe = tally[target]
        return {"shown": sorted(shown), "numbers": {str(i): numbers[i] for i in sorted(shown)}, "target": target,
                "status": want, "p_mine": round(w_mine / (w_mine + w_safe), 6), "truth": "mine" if target in mines else "safe"}

    def label_of(self, record):
        return record["status"]

    def to_item(self, record, rng):
        shown = set(record["shown"])
        numbers = {int(k): v for k, v in record["numbers"].items()}
        question = Question(type="choice", criteria=shuffled_options(STATUS, rng), instructions=(
            f"Minesweeper, Beginner board: {ROWS} rows (A-I) by {COLS} columns (1-9) with {MINES} mines in total, none flagged. "
            "'#' is a covered square; a number tells how many of the eight surrounding squares hold a mine; '.' is an uncovered "
            f"square with no adjacent mine. What can be concluded about the covered square {square_name(record['target'])}?"))
        state = {"board": render_minefield(shown, numbers), "square": square_name(record["target"])}
        return self.item(state, {"square_status": question}, {"square_status": Gold(label=record["status"])},
                         p_mine=record["p_mine"], actual=record["truth"])
